"""Recover our known Actions artifact and normalize legacy NumPy integer metadata.

Only use with the trusted checkpoint generated by this repository's earlier run.
No unrestricted pickle loading is enabled.
"""
import argparse
from pathlib import Path
import shutil
import numpy as np
import torch


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--destination", type=Path, default=Path("."))
    args = parser.parse_args()
    for relative in ("results/breakout", "screenshots"):
        shutil.copytree(args.source / relative, args.destination / relative)
    checkpoint_path = args.destination / "results/breakout/checkpoint.pt"
    # Scoped allowlist for the single np.int64 action count in our old checkpoint.
    from numpy._core.multiarray import scalar
    with torch.serialization.safe_globals([scalar, np.dtype, type(np.dtype(np.int64))]):
        checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    checkpoint["action_count"] = int(checkpoint["action_count"])
    torch.save(checkpoint, checkpoint_path)
    verified = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    print("Recovered training step", verified["step"], "with", verified["updates"], "updates")


if __name__ == "__main__":
    main()
